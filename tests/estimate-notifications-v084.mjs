import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { notificationConfig, providerStatus } from '../server/lib/estimate-notifications.mjs';
const seed=JSON.parse(await readFile(new URL('../server/data/production-seed.json',import.meta.url),'utf8'));
const cfg=notificationConfig(seed.tenant);
assert.equal(cfg.email,seed.tenant.email);
assert.deepEqual(Object.keys(cfg),['email']);
const providers=providerStatus();
assert.equal(typeof providers.emailConfigured,'boolean');
assert.equal('smsConfigured' in providers,false);
const server=await readFile(new URL('../server/server.mjs',import.meta.url),'utf8');
assert.match(server,/await storage\.write\(db\);lead\.notificationStatus=await notifyEstimate/,'estimate must be saved before notification attempt');
assert.match(server,/Estimate notification · email/);
const app=await readFile(new URL('../app/app.js',import.meta.url),'utf8');
assert.ok(app.includes('Estimate Notification Email'));
assert.ok(app.includes('Call Paradise'));
assert.ok(app.includes('Text Paradise'));
assert.ok(!app.includes('Estimate Notification Phone'));
assert.ok(!app.includes('Estimate Notification Preference'));
const lib=await readFile(new URL('../server/lib/estimate-notifications.mjs',import.meta.url),'utf8');
assert.ok(lib.includes('SENDGRID_API_KEY'));
for(const token of ['TWILIO_ACCOUNT_SID','TWILIO_AUTH_TOKEN','TWILIO_FROM_NUMBER','sendSms','smsConfigured'])assert.ok(!lib.includes(token),`removed SMS provider token still present: ${token}`);
const site=await readFile(new URL('../website/assets/site.js',import.meta.url),'utf8');
assert.match(site,/href=\"tel:\$\{phoneDigits\}\"/);
assert.match(site,/href=\"sms:\$\{phoneDigits\}\?body=\$\{textBody\}\"/);
assert.ok(site.includes('You choose whether to press Send'));
assert.ok(!site.includes('window.location.href=`mailto:'));
console.log('estimate contact v0.8.6 contract passed');
